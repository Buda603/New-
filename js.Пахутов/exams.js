function split(arr) {
//Объявляется функция с именем split, которая принимает один параметр arr (массив).    
    let pos = [], neg = [];
//Создаются два пустых массива:    
    for (let x of arr) {
//Запускается цикл for...of, который перебирает каждый элемент массива arr. На каждой итерации текущий элемент сохраняется в переменную x.        
        if (x > 0) pos.push(x);
//Если текущее число x больше нуля (положительное), оно добавляется в конец массива pos с помощью метода push().         
        if (x < 0) neg.push(x);
// Если текущее число x меньше нуля (отрицательное), оно добавляется в конец массива neg.        
    }
    return [pos, neg];
//Функция возвращает массив из двух элементов: первый элемент - массив положительных чисел, второй - массив отрицательных чисел.
}
let n = +prompt("N:");
// Запрашивает у пользователя через всплывающее окно количество чисел, которое он хочет ввести. Результат (строка) сохраняется в переменной n.
let a = [];
// Создается пустой массив a, в который будут добавлены все введенные числа.
for (let i = 0; i< n; i++) a.push(+prompt(i+1))
// Запускается цикл for от i = 0 до i < n
// На каждой итерации вызывается prompt(i+1), который показывает номер ввода (например, "1", "2" и т.д.)
// Знак + перед prompt преобразует строку от пользователя в число
// Число добавляется в массив a методом push()    
let [p, ng] = split(a);
//Вызывается функция split с массивом a
// Функция возвращает массив [pos, neg]
// Используется деструктуризация массива: первый элемент (положительные числа) сохраняется в переменную p, второй (отрицательные) - в переменную ng
console.log("Исходный массив:", a);
console.log("Положительные:", p);
console.log("Отрицательные:", ng);  